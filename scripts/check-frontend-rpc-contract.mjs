#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoots = ["web/app", "web/lib", "web/components"];
const verifyPath = path.join(repoRoot, "supabase/verify/frontend_rpc_contract_verify.sql");
const sourceExtensions = new Set([".js", ".jsx", ".ts", ".tsx"]);
const ignoredDirectories = new Set([".next", "node_modules"]);
const writeMode = process.argv.includes("--write");

const fail = (message) => {
  console.error(`ERROR: ${message}`);
  process.exit(1);
};

const walk = (directory) => {
  const entries = fs.readdirSync(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    if (entry.isDirectory()) {
      if (!ignoredDirectories.has(entry.name)) {
        files.push(...walk(path.join(directory, entry.name)));
      }
      continue;
    }

    if (entry.isFile() && sourceExtensions.has(path.extname(entry.name))) {
      files.push(path.join(directory, entry.name));
    }
  }

  return files;
};

const rpcNames = new Set();
const rpcPattern = /(?:\w+\.)?rpc\s*\(\s*["']([A-Za-z0-9_]+)["']/g;

for (const sourceRoot of sourceRoots) {
  const absoluteRoot = path.join(repoRoot, sourceRoot);
  if (!fs.existsSync(absoluteRoot)) {
    continue;
  }

  for (const file of walk(absoluteRoot)) {
    const source = fs.readFileSync(file, "utf8");
    for (const match of source.matchAll(rpcPattern)) {
      rpcNames.add(match[1]);
    }
  }
}

const sortedRpcNames = [...rpcNames].sort();

if (sortedRpcNames.length === 0) {
  fail("no frontend RPC calls were found; check sourceRoots or parser pattern.");
}

const values = sortedRpcNames
  .map((name) => `      ('${name}')`)
  .join(",\n");

const generatedSql = `-- Generated by scripts/check-frontend-rpc-contract.mjs --write.
-- Verifies that every RPC called by web/app, web/lib, and web/components
-- exists in the public schema of the target Supabase database.

do $$
declare
  v_missing jsonb;
begin
  with frontend_rpc(name) as (
    values
${values}
  ), live_public_rpc as (
    select distinct p.proname as name
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
  )
  select coalesce(jsonb_agg(f.name order by f.name), '[]'::jsonb)
  into v_missing
  from frontend_rpc f
  left join live_public_rpc live using (name)
  where live.name is null;

  if jsonb_array_length(v_missing) > 0 then
    raise exception 'FAIL: frontend RPC contract missing functions: %', v_missing;
  end if;
end;
$$;
`;

if (writeMode) {
  fs.writeFileSync(verifyPath, generatedSql);
  console.log(`Wrote ${path.relative(repoRoot, verifyPath)} with ${sortedRpcNames.length} RPC names.`);
  process.exit(0);
}

const currentSql = fs.existsSync(verifyPath)
  ? fs.readFileSync(verifyPath, "utf8")
  : "";

if (currentSql !== generatedSql) {
  console.error(`${path.relative(repoRoot, verifyPath)} is out of date.`);
  console.error("Run: node scripts/check-frontend-rpc-contract.mjs --write");
  process.exit(1);
}

console.log(`PASS: frontend RPC contract lists ${sortedRpcNames.length} RPC names.`);
