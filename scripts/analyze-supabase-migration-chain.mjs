#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = path.join(repoRoot, "supabase/migrations");
const reportPath = path.join(repoRoot, "supabase/review/migration_chain_reconciliation.generated.md");
const activeMigrationFloor = "20260818180000";

const filePattern = /^(\d{8}|\d{14})_(.+)\.sql$/;
const schemaQualifiedRelation =
  /(?:\bpublic\.|"public"\s*\.\s*")([a-zA-Z_][a-zA-Z0-9_]*)"?/g;
const createRelationPatterns = [
  /\bcreate\s+(?:unlogged\s+)?table\s+(?:if\s+not\s+exists\s+)?(?:"public"\s*\.\s*"|public\.)([a-zA-Z_][a-zA-Z0-9_]*)"?/gi,
  /\bcreate\s+(?:or\s+replace\s+)?view\s+(?:if\s+not\s+exists\s+)?(?:"public"\s*\.\s*"|public\.)([a-zA-Z_][a-zA-Z0-9_]*)"?/gi,
  /\bcreate\s+materialized\s+view\s+(?:if\s+not\s+exists\s+)?(?:"public"\s*\.\s*"|public\.)([a-zA-Z_][a-zA-Z0-9_]*)"?/gi,
  /\bcreate\s+sequence\s+(?:if\s+not\s+exists\s+)?(?:"public"\s*\.\s*"|public\.)([a-zA-Z_][a-zA-Z0-9_]*)"?/gi,
];
const functionMutationPatterns = [
  /\bpg_get_functiondef\s*\(/i,
  /\bexecute\s+replace\s*\(/i,
  /\bexecute\s+regexp_replace\s*\(/i,
  /\bexecute\s+v_definition\b/i,
  /\bexecute\s+definition\b/i,
  /\bexecute\s+function_definition\b/i,
];

const files = fs.readdirSync(migrationsDir)
  .filter((file) => file.endsWith(".sql"))
  .sort();

const migrationRows = files.map((file) => {
  const fullPath = path.join(migrationsDir, file);
  const sql = fs.readFileSync(fullPath, "utf8");
  const match = file.match(filePattern);
  const createdRelations = new Set();
  const referencedRelations = new Set();

  for (const pattern of createRelationPatterns) {
    for (const relationMatch of sql.matchAll(pattern)) {
      createdRelations.add(relationMatch[1]);
    }
  }

  for (const relationMatch of sql.matchAll(schemaQualifiedRelation)) {
    referencedRelations.add(relationMatch[1]);
  }

  for (const relation of createdRelations) {
    referencedRelations.delete(relation);
  }

  return {
    file,
    version: match?.[1] ?? null,
    slug: match?.[2] ?? null,
    sql,
    createdRelations: [...createdRelations].sort(),
    referencedRelations: [...referencedRelations].sort(),
    hasFunctionBodyMutation: functionMutationPatterns.some((pattern) => pattern.test(sql)),
    isMisplacedCompanion: /_(rollback|verify)\.sql$/i.test(file),
  };
});

const relationFirstCreate = new Map();
for (const row of migrationRows) {
  for (const relation of row.createdRelations) {
    if (!relationFirstCreate.has(relation)) {
      relationFirstCreate.set(relation, row.file);
    }
  }
}

const relationRefRows = [];
for (const row of migrationRows) {
  for (const relation of row.referencedRelations) {
    const firstCreate = relationFirstCreate.get(relation) ?? null;
    if (!firstCreate || firstCreate > row.file) {
      relationRefRows.push({
        file: row.file,
        relation,
        firstCreate,
      });
    }
  }
}

const relationRefSummary = new Map();
for (const ref of relationRefRows) {
  const summary = relationRefSummary.get(ref.relation) ?? {
    relation: ref.relation,
    firstCreate: ref.firstCreate,
    count: 0,
    firstReferences: [],
  };
  summary.count += 1;
  if (summary.firstReferences.length < 6) {
    summary.firstReferences.push(ref.file);
  }
  relationRefSummary.set(ref.relation, summary);
}

const mutationFiles = migrationRows
  .filter((row) => row.hasFunctionBodyMutation)
  .map((row) => row.file);
const misplacedCompanions = migrationRows
  .filter((row) => row.isMisplacedCompanion)
  .map((row) => row.file);
const legacyShortVersionFiles = migrationRows
  .filter((row) => row.version?.length === 8)
  .map((row) => row.file);
const activeFiles = migrationRows
  .filter((row) => row.version?.length === 14 && row.version >= activeMigrationFloor)
  .map((row) => row.file);

const topRelationRefs = [...relationRefSummary.values()]
  .sort((a, b) => b.count - a.count || a.relation.localeCompare(b.relation))
  .slice(0, 25);

const lines = [];
lines.push("# Migration Chain Reconciliation");
lines.push("");
lines.push("Generated by `scripts/analyze-supabase-migration-chain.mjs --write`.");
lines.push("");
lines.push("## Summary");
lines.push("");
lines.push(`- Migration files scanned: ${migrationRows.length}`);
lines.push(`- Legacy 8-digit migration files: ${legacyShortVersionFiles.length}`);
lines.push(`- Active 14-digit migration files at/after \`${activeMigrationFloor}\`: ${activeFiles.length}`);
lines.push(`- Files with function-body mutation patterns: ${mutationFiles.length}`);
lines.push(`- Rollback/verify companion files currently inside \`supabase/migrations\`: ${misplacedCompanions.length}`);
lines.push(`- Public relations referenced before local creation, or never locally created: ${relationRefSummary.size}`);
lines.push("");
lines.push("## Branch Replay Failure");
lines.push("");
lines.push("The Supabase preview branch failed automatic migration replay at:");
lines.push("");
lines.push("```text");
lines.push("supabase/migrations/20260730_anonymous_progress_transfer_hardening.sql");
lines.push("relation \"public.user_abilities\" does not exist");
lines.push("```");
lines.push("");
const userAbility = relationRefSummary.get("user_abilities");
if (userAbility) {
  lines.push("The local chain confirms the same problem:");
  lines.push("");
  lines.push(`- \`public.user_abilities\` is referenced by ${userAbility.count} migration file(s).`);
  lines.push(`- Local create migration found: ${userAbility.firstCreate ? `\`${userAbility.firstCreate}\`` : "none"}.`);
  lines.push("- First references:");
  for (const file of userAbility.firstReferences) {
    lines.push(`  - \`${file}\``);
  }
} else {
  lines.push("The analyzer did not find schema-qualified `public.user_abilities` references.");
}
lines.push("");
lines.push("This proves the local migration directory is a historical patch log, not a clean rebuild source.");
lines.push("");
lines.push("## Top Relation Replay Risks");
lines.push("");
lines.push("| Relation | Reference count | Local create | First references |");
lines.push("|---|---:|---|---|");
for (const item of topRelationRefs) {
  lines.push(
    `| \`public.${item.relation}\` | ${item.count} | ${item.firstCreate ? `\`${item.firstCreate}\`` : "none"} | ${item.firstReferences.map((file) => `\`${file}\``).join("<br>")} |`,
  );
}
lines.push("");
lines.push("These are static findings. Some relations may exist because they were created outside the local migration chain or in migrations that used unqualified names. Treat this as a triage list, not automatic deletion or rewrite authority.");
lines.push("");
lines.push("## Function Body Mutation Files");
lines.push("");
if (mutationFiles.length === 0) {
  lines.push("No files matched the mutation patterns.");
} else {
  for (const file of mutationFiles) {
    lines.push(`- \`${file}\``);
  }
}
lines.push("");
lines.push("These files make rebuild reasoning difficult because the final function body depends on the previous production body and exact string anchors.");
lines.push("");
lines.push("## Misplaced Companion Files");
lines.push("");
if (misplacedCompanions.length === 0) {
  lines.push("No rollback/verify companion files were found inside `supabase/migrations`.");
} else {
  for (const file of misplacedCompanions) {
    lines.push(`- \`${file}\``);
  }
}
lines.push("");
lines.push("Rollback and verification SQL should live in `supabase/rollback` and `supabase/verify`, not in the migration replay path.");
lines.push("");
lines.push("## Recommended Reconciliation Strategy");
lines.push("");
lines.push("1. Keep the verified schema baseline as the current source-of-truth artifact for understanding production shape.");
lines.push("2. Do not try to make every historical migration replayable one-by-one; several assume production objects or mutate old function bodies.");
lines.push("3. Create a new baseline migration chain for future development, with old migrations archived outside the replay path.");
lines.push("4. Preserve historical SQL under an archive/review directory so definitions remain searchable.");
lines.push("5. From the baseline forward, require one forward migration, one rollback, and one verifier per change.");
lines.push("6. Use Supabase branch restores and advisor checks to test cleanup batches before production.");

const shouldWrite = process.argv.includes("--write");
const shouldCheck = process.argv.includes("--check");
const report = `${lines.join("\n")}\n`;

if (shouldWrite) {
  fs.mkdirSync(path.dirname(reportPath), { recursive: true });
  fs.writeFileSync(reportPath, report);
}

if (shouldCheck) {
  const existingReport = fs.existsSync(reportPath)
    ? fs.readFileSync(reportPath, "utf8")
    : "";

  if (existingReport !== report) {
    console.error("FAIL: migration chain reconciliation report is stale.");
    console.error("Run: node scripts/analyze-supabase-migration-chain.mjs --write");
    process.exit(1);
  }
}

console.log(`Migration files scanned: ${migrationRows.length}`);
console.log(`Legacy 8-digit migration files: ${legacyShortVersionFiles.length}`);
console.log(`Active migration files: ${activeFiles.length}`);
console.log(`Function body mutation files: ${mutationFiles.length}`);
console.log(`Misplaced companion files: ${misplacedCompanions.length}`);
console.log(`Public relation replay-risk entries: ${relationRefSummary.size}`);
if (shouldWrite) {
  console.log(`Wrote ${path.relative(repoRoot, reportPath)}`);
}
if (shouldCheck) {
  console.log("PASS: migration chain reconciliation report is current.");
}
