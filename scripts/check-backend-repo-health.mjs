#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = path.join(repoRoot, "supabase/migrations");
const rollbackDir = path.join(repoRoot, "supabase/rollback");
const verifyDir = path.join(repoRoot, "supabase/verify");

const activeMigrationFloor = "20260818180000";
const sqlFilePattern = /^(\d{8}|\d{14})_(.+)\.sql$/;
const badMutationPatterns = [
  /\bexecute\s+replace\s*\(/i,
  /\bexecute\s+regexp_replace\s*\(/i,
  /\bexecute\s+v_definition\b/i,
  /\bexecute\s+definition\b/i,
  /\bexecute\s+function_definition\b/i,
];

const listSqlFiles = (directory) =>
  fs.readdirSync(directory)
    .filter((file) => file.endsWith(".sql"))
    .sort();

const migrationFiles = listSqlFiles(migrationsDir);
const rollbackFiles = new Set(listSqlFiles(rollbackDir));
const verifyFiles = new Set(listSqlFiles(verifyDir));
const failures = [];
const warnings = [];
const versions = new Map();

for (const file of migrationFiles) {
  const match = file.match(sqlFilePattern);
  if (!match) {
    failures.push(`Migration filename is not versioned: ${file}`);
    continue;
  }

  const [, version, slug] = match;
  versions.set(version, [...(versions.get(version) ?? []), file]);

  if (version.length !== 14) {
    warnings.push(`Legacy short migration version: ${file}`);
    continue;
  }

  if (version < activeMigrationFloor) {
    continue;
  }

  const expectedRollback = `${version}_${slug}_rollback.sql`;
  const expectedVerify = `${version}_${slug}_verify.sql`;

  if (!rollbackFiles.has(expectedRollback)) {
    failures.push(`Active migration missing rollback companion: ${expectedRollback}`);
  }

  if (!verifyFiles.has(expectedVerify)) {
    failures.push(`Active migration missing verify companion: ${expectedVerify}`);
  }

  const sql = fs.readFileSync(path.join(migrationsDir, file), "utf8");
  if (badMutationPatterns.some((pattern) => pattern.test(sql))) {
    failures.push(`Active migration uses function-body mutation pattern: ${file}`);
  }

  if (!/\bset\s+local\s+lock_timeout\b/i.test(sql)) {
    warnings.push(`Active migration does not set lock_timeout: ${file}`);
  }

  if (!/\bcommit\s*;/i.test(sql)) {
    warnings.push(`Active migration is not explicitly transaction-wrapped: ${file}`);
  }
}

for (const [version, files] of versions) {
  if (files.length > 1 && version.length === 14 && version >= activeMigrationFloor) {
    failures.push(`Duplicate active 14-digit migration version ${version}: ${files.join(", ")}`);
  }
}

const frontendContractPath = path.join(verifyDir, "frontend_rpc_contract_verify.sql");
const frontendContract = fs.existsSync(frontendContractPath)
  ? fs.readFileSync(frontendContractPath, "utf8")
  : "";

if (!frontendContract.startsWith("-- Generated by scripts/check-frontend-rpc-contract.mjs --write.")) {
  failures.push("frontend_rpc_contract_verify.sql is not marked as generated.");
}

for (const requiredVerify of [
  "frontend_rpc_contract_verify.sql",
  "load_bearing_rpc_chain_verify.sql",
  "security_definer_client_surface_verify.sql",
]) {
  if (!verifyFiles.has(requiredVerify)) {
    failures.push(`Missing backend contract verifier: ${requiredVerify}`);
  }
}

if (failures.length > 0) {
  console.error("Backend repo health check failed:");
  for (const failure of failures) {
    console.error(`  - ${failure}`);
  }
  if (warnings.length > 0) {
    console.error("\nWarnings:");
    for (const warning of warnings.slice(0, 20)) {
      console.error(`  - ${warning}`);
    }
    if (warnings.length > 20) {
      console.error(`  - ... ${warnings.length - 20} more warnings`);
    }
  }
  process.exit(1);
}

console.log("PASS: backend repo health gates are satisfied.");
console.log(`Active migration floor: ${activeMigrationFloor}`);
console.log(`Migrations scanned: ${migrationFiles.length}`);
console.log(`Warnings: ${warnings.length}`);
